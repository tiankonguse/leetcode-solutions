typedef long long ll;
class Solution {
 public:
  int countValidPrefixes(string s) {
    int cnt[2] = {0, 0};
    int ans = 0;
    for (auto c : s) {
      cnt[c - '0']++;
      if (abs(cnt[0] - cnt[1]) <= 1) {
        ans++;
      }
    }
    return ans;
  }
};

